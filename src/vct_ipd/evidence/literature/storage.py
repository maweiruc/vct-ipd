"""Auditable collection output; source access permissions control text caching."""
import json
from pathlib import Path
from .retrieval import sha


def save_collection(collection, destination, *, adoption=None, run_written=False):
    root = Path(destination)
    if run_written:
        root = root / 'literature'
    root.mkdir(parents=True, exist_ok=False)
    def save(name, value):
        path = root / name; path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + '\n')
    save('request.json', collection.request.model_dump())
    save('retrieval/searches.json', {'mode': collection.retrieval.mode, 'calls': collection.retrieval.calls,
                                    'status': collection.retrieval.status, 'searches': collection.retrieval.searches,
                                    'diagnostics': collection.retrieval.diagnostics})
    docs = []
    for doc in collection.retrieval.documents:
        data = doc.model_dump(); data.pop('text')
        data['cached_text'] = None
        if doc.cache_text and doc.text:
            name = 'texts/' + sha(doc.id)[:24] + '.txt'
            path = root / name; path.parent.mkdir(parents=True, exist_ok=True); path.write_text(doc.text)
            data['cached_text'] = name
        docs.append(data)
    save('retrieval/documents.json', docs)
    save('extraction/drafts.json', collection.draft.model_dump())
    save('extraction/provider.json', collection.extraction_metadata)
    save('extraction/validation.json', {'status': collection.status, 'diagnostics': collection.diagnostics,
        'candidates': [v.model_dump() for v in collection.batch.validation], 'conflicts': collection.batch.conflicts})
    save('evidence.json', [e.model_dump(mode='json') for e in collection.batch.validated])
    if adoption:
        save('adoption.json', adoption.model_dump())
    lines = ['# Literature evidence collection', '', f'Status: **{collection.status}**',
             f'Retrieval mode: {collection.retrieval.mode}; calls: {collection.retrieval.calls}.',
             f'Validated Evidence objects: {len(collection.batch.validated)}; conflicts: {len(collection.batch.conflicts)}.',
             'Validation establishes only the supported source-text/type checks; adoption and clinical applicability are separate.',
             'No cohort is generated by collect-only. Real or unreviewed sources cannot activate the hypothetical demo.', '',
             'Original target description:', '', collection.request.target_description, '',
             '| Candidate | Status | Reasons |', '| --- | --- | --- |']
    lines.extend(f'| {v.index} | {v.status} | {"; ".join(v.reasons)} |' for v in collection.batch.validation)
    lines.extend(['', *collection.diagnostics, *collection.retrieval.diagnostics])
    (root/'report.md').write_text('\n'.join(lines) + '\n')
    return root
